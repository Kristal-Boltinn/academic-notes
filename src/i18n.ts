export type Message = keyof typeof ENGLISH;
let current: 'en' | 'zh' = 'en';
export function setLanguage(locale: string) { current = /^zh(?:[-_]|$)/i.test(locale) ? 'zh' : 'en'; }
export function language() { return current; }
export function t(key: Message, ...values: unknown[]): string {
    const text = current === 'zh' ? key : ENGLISH[key];
    return text.replace(/\{(\d+)\}/g, (match, index: string) => Number(index) < values.length ? String(values[Number(index)]) : match);
}
